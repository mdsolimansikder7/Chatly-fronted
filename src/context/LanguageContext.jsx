const LanguageContext = createContext(null);

function initialLanguage() {
  const savedLanguage = localStorage.getItem("chatly-language");
  if (savedLanguage === "bn" || savedLanguage === "en") return savedLanguage;
  return navigator.language.startsWith("bn") ? "bn" : "en";
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(initialLanguage);

  useEffect(() => {
    document.documentElement.lang = language === "bn" ? "bn" : "en";
    localStorage.setItem("chatly-language", language);
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    locale: language === "bn" ? "bn-BD" : "en-US",
    t: (key, values = {}) => (translations[language][key] || translations.en[key] || key)
      .replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`),
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
